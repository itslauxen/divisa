    /// HID → kVK.
    static let doHID: [Int: CGKeyCode] = Dictionary(paraHID.map { ($0.value, $0.key) }, uniquingKeysWith: { a, _ in a })

    /// Bit de cada modificador nos flags do evento (máscaras NX_DEVICE*, que separam esquerdo e direito).
    static let mascaraDoModificador: [CGKeyCode: UInt64] = [
        0x3B: 0x0000_0001, // Control esquerdo
        0x38: 0x0000_0002, // Shift esquerdo
        0x3C: 0x0000_0004, // Shift direito
        0x37: 0x0000_0008, // Command esquerdo
        0x36: 0x0000_0010, // Command direito
        0x3A: 0x0000_0020, // Option esquerdo
        0x3D: 0x0000_0040, // Option direito
        0x3E: 0x0000_2000, // Control direito
    ]

    /// Flag geral (Command, Shift…) que cada modificador liga, para os eventos injetados levarem o estado certo.
    static let flagDoModificador: [CGKeyCode: CGEventFlags] = [
        0x3B: .maskControl, 0x3E: .maskControl,
        0x38: .maskShift, 0x3C: .maskShift,
        0x37: .maskCommand, 0x36: .maskCommand,
        0x3A: .maskAlternate, 0x3D: .maskAlternate,
    ]

    /// Esc: usado no atalho de emergência.
    static let esc: CGKeyCode = 0x35
}
